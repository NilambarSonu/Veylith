function main() {
  const repoRoot = resolve(fileURLToPath(new URL('../..', import.meta.url)));
  const outDir = resolve(repoRoot, 'security-lab/phase-5');
  mkdirSync(outDir, { recursive: true });

  const datasetPath = resolve(outDir, 'dataset.json');
  const manifestPath = resolve(outDir, 'dataset-manifest.json');

  const jsonContent = JSON.stringify(cases, null, 2);
  writeFileSync(datasetPath, jsonContent);

  const sha256 = createHash('sha256').update(jsonContent).digest('hex');

  const summary = {
    totalCases: cases.length,
    maliciousCases: cases.filter((c) => c.classification === 'malicious').length,
    benignCases: cases.filter((c) => c.classification === 'benign').length,
    categories: {
      direct_injection: cases.filter((c) => c.category === 'direct_injection').length,
      indirect_injection: cases.filter((c) => c.category === 'indirect_injection').length,
      role_hijacking: cases.filter((c) => c.category === 'role_hijacking').length,
      obfuscated_multilingual: cases.filter((c) => c.category === 'obfuscated_multilingual').length,
      dangerous_arguments: cases.filter((c) => c.category === 'dangerous_arguments').length,
    },
    difficulties: {
      easy: cases.filter((c) => c.difficulty === 'easy').length,
      medium: cases.filter((c) => c.difficulty === 'medium').length,
      hard: cases.filter((c) => c.difficulty === 'hard').length,
    },
    datasetSha256: sha256,
    generatedAt: new Date().toISOString(),
  };

  writeFileSync(manifestPath, JSON.stringify(summary, null, 2));

  console.log('Phase 5 Live Evaluation Dataset Generated:');
  console.log(`- Path       : ${datasetPath}`);
  console.log(`- Total Cases: ${summary.totalCases} (50 Malicious / 50 Benign)`);
  console.log(`- SHA-256    : ${sha256}`);
  console.log(`- Manifest   : ${manifestPath}`);
}

main();

